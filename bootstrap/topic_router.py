@lru_cache(maxsize=4096)
def _normalized(text):
    value = unicodedata.normalize("NFKC", text).casefold().replace("ё", "е")
    return " ".join(re.findall(r"[a-zа-я0-9]+", value))


def _has_stem(words, stem):
    parts = stem.split()
    if len(parts) == 1:
        return any(word.startswith(stem) for word in words)
    return any(
        all(words[i + j].startswith(part) for j, part in enumerate(parts))
        for i in range(len(words) - len(parts) + 1)
    )


def classify(text):
    """Возвращает только категории с убедительной локальной поддержкой.

    Несколько тем допустимы, когда *каждая* подтверждается одним утверждением,
    а не случайными словами из совершенно других страниц документа.
    """
    words = _normalized(text).split()
    scores = {}
    for topic, rules in TOPICS.items():
        score = sum(weight for stem, weight in rules if _has_stem(words, stem))
        if score >= 3:
            scores[topic] = score
    if not scores:
        return ["Общие знания"]
    ordered = sorted(scores, key=lambda topic: (-scores[topic], topic))
    first = ordered[0]
    selection = [first]
    if len(ordered) > 1:
        second = ordered[1]
        if scores[second] >= 5 and scores[second] >= scores[first] * 0.75:
            selection.append(second)
    return selection


def choose_child(topic, text):
    """Подраздел подбирается по *текущему* утверждению, не по целой книге."""
    words = _normalized(text).split()
    for title, stems in CHILD_KEYWORDS.get(topic, ()):
        if any(_has_stem(words, stem) for stem in stems):
            return title
    return None
